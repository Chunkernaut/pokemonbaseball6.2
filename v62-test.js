'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const B=require('./engine');
const app=fs.readFileSync('./public/app.js','utf8');
const html=fs.readFileSync('./public/index.html','utf8');
const css=fs.readFileSync('./public/style.css','utf8');
assert.equal((html.match(/id="global-scout-guide"/g)||[]).length,1,'One guide, shared between all views');
assert.ok(html.indexOf('id="global-scout-guide"')>html.indexOf('</main>'), 'Guide placed after every main view');
assert.equal((app.match(/\$\{weightGuide\(\)\}/g)||[]).length,0,'Guide not copied into dynamic view content');
assert.match(app,/setupPersistentGuide\(\)/);
assert.match(app,/section\.open=localStorage\.getItem\('pb-guide-expanded'\)/);
assert.match(app,/section\.addEventListener\('toggle'/);
const guideSource=app.slice(app.indexOf('function weightGuide(){'),app.indexOf('function setupPersistentGuide()'));
assert.doesNotMatch(guideSource,/\.toFixed\(|Math\.round\(r\.stats|\*100\}%/,'No formula weights displayed');
for(const label of ['HP:','Attack:','Defense:','Sp. Attack:','Sp. Defense:','Speed:','Height & weight:','Batting order explained','Stamina, substitutions & the bench','Position priorities'])assert.ok(guideSource.includes(label),label);
assert.ok(!app.includes('toggle-formula')&&!app.includes('formula-table'));
assert.match(app,/data-batto/);
assert.match(app,/data-bat-shuffle/);
assert.match(app,/data-scroll-batting/);
assert.match(css,/\.batting-jump/);
const r=Object.fromEntries(B.SLOTS.map((slot,i)=>[slot.id,i+1]));
const order=B.seededOrder(r,1414);
assert.equal(B.validateBattingOrder(r,order),true);
const rearranged=[...order],moved=rearranged.splice(0,1);rearranged.splice(8,0,...moved);
assert.equal(rearranged[8],order[0]);
assert.equal(B.validateBattingOrder(r,rearranged),true);
console.log('PASS v6.2: persistent, percentage-free guide on all views; newbie batting-order controls; valid order moves.');
